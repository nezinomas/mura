    <div class="mura-page">

        <div class="prose max-w-none leading-relaxed text-sm text-base-content prose-headings:font-mura prose-headings:font-normal prose-h3:text-lg prose-a:text-base-content hover:prose-a:opacity-70">

            <p class="italic opacity-70 mb-12">
                This space is designed to be a quiet, analog reflection of thoughts. To maintain the integrity of this environment, we observe the following principles.
            </p>

            <h3 class="mura-rule-heading">1. A Single Breath (Length)</h3>
            <p>
                A thought here is brief by design — no more than a thousand characters. Say the true thing, then stop. Brevity is not a limit; it is the discipline of the form.
            </p>

            <h3 class="mura-rule-heading mt-8">2. Plain Ink (Formatting)</h3>
            <p>
                A little emphasis is welcome — a word in bold, a phrase in italics, a link to somewhere quiet — but no more. Headlines, images, and louder declarations are gently stripped away. The page favours the sentence over the spectacle.
            </p>

            <h3 class="mura-rule-heading mt-8">3. The Ink Dries (Editing)</h3>
            <p>
                You have a 24-hour window to mend a fresh thought — a typo, an immediate regret. After that the ink dries, and the thought is sealed permanently in its current state.
            </p>

            <h3 class="mura-rule-heading mt-8">4. Behind the Curtain (Privacy)</h3>
            <p>
                A private thought is for your eyes alone — kept from every feed, every stranger, every search but your own. A public one steps into the shared room and may be Grabbed; once it has, it can no longer be drawn back behind the curtain. Choose the curtain before you speak, not after.
            </p>

            <h3 class="mura-rule-heading mt-8">5. No Applause (Reactions)</h3>
            <p>
                There are no hearts to collect here, no counters ticking upward, no comment threads to tend. A thought is offered, not performed. Its worth is never measured by how many nodded along — and you will never be told how many did.
            </p>

            <h3 class="mura-rule-heading mt-8">6. Borrowed, Not Owned (Grabbing)</h3>
            <p>
                When a thought moves you, you may Grab it and keep it among your own — a page copied by hand into your notebook, not torn from theirs. The words remain the author's. Hold what you gather with the care you would want for your own.
            </p>

            <h3 class="mura-rule-heading mt-8">7. Tearing the Page (Deletion)</h3>
            <p>
                You may delete a thought at any time. If no one has Grabbed it, it is gone. If someone has, it is not erased but disowned — your name stripped from it, left in the commons as an anonymous, orphaned fragment.
            </p>

            <h3 class="mura-rule-heading mt-8">8. Lost in Time (Departure)</h3>
            <p>
                Should you choose to leave entirely, your unheld thoughts leave with you. The same rule holds for the rest: any that others have Grabbed remain, stripped of your name. Nothing you have given away is ever fully recalled.
            </p>

            <h3 class="mura-rule-heading mt-8">9. One True Name (Identity)</h3>
            <p>
                Carry a single name, and let it be recognisably yours. Do not wear another's face, nor pose as the keeper of this house. This is a small room, and trust is its only furniture.
            </p>

            <h3 class="mura-rule-heading mt-8">10. Keeping the Peace (Conduct)</h3>
            <p>
                This is a place for observation, poetry, and quiet reflection — not a battleground. Hate speech, harassment, deliberate cruelty, or incitement to violence will be removed, and accounts that return to it closed without appeal.
            </p>

            <h3 class="mura-rule-heading mt-8">11. The Keeper's Desk (Correspondence)</h3>
            <p>
                A question, a concern, or a quiet word for the one who tends this place may be left at the Correspondence desk. It is read slowly, and answered in kind.
            </p>

            <p class="italic opacity-70 mt-12">
                Write as if the page will outlast you — quietly, and only what is true.
            </p>

        </div>
    </div>
